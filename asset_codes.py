"""Справочник буквенных обозначений техники и выдача инвентарных номеров.

Инвентарный номер имеет вид ``ПРЕФИКС-NNNN``: буквы говорят, что это за
техника, четыре цифры — сквозной номер по всему складу, общий для всех
типов. Ноутбук, добавленный после ``MON-0050``, получает ``NB-0051``.

Правила живут здесь, а не в браузере, потому что первым их потребителем
является миграция перенумерации (``migrations._migrate_028``), которая
работает на сервере без всякого JS. Десктоп и мобильное приложение
получают тот же справочник через ``GET /api/state`` полем
``assetCodeTypes`` — так список существует в одном экземпляре, и его не
приходится сверять между Python и JS.

Файл намеренно не импортирует ничего из ``server``: как и
``mobile_actions``, он должен тестироваться сам по себе.
"""

from __future__ import annotations

import re
import sqlite3

# (префикс, название для справочника, ключевые слова)
#
# ПОРЯДОК ЗНАЧИМ — побеждает первое совпавшее правило, и несколько пар
# правил стоят именно так не случайно:
#
#   AIO перед PC     "ПК - моноблок" содержит "пк";
#   MFP перед PRN    "Принтер / Сканер" содержит "принтер";
#   MFP перед SCN    оно же содержит "сканер";
#   HPH перед TEL    "наушники" не должны ловиться на "phone";
#   UPS перед AVR    ИБП в базе называется "UPS (ИБП) AVT-650 AVR, 650ВА".
#
# Тесты в tests/test_asset_codes.py фиксируют каждую из этих пар, так что
# перестановка строк уронит сборку, а не тихо переименует технику.
ASSET_CODE_RULES: list[tuple[str, str, tuple[str, ...]]] = [
    ("AIO", "ПК-моноблок", ("моноблок", "all-in-one", "all in one", "a i o pc")),
    ("PC", "Системный блок", ("системный блок", "системник", "пк")),
    ("NB", "Ноутбук", ("ноутбук", "laptop", "notebook")),
    ("TAB", "Планшет", ("планшет", "tablet", "galaxy tab")),
    ("SVR", "Сервер", ("сервер", "server")),
    ("MON", "Монитор", ("монитор", "monitor", "дисплей")),
    ("KEY", "Клавиатура", ("клавиатура", "keyboard")),
    ("MUS", "Мышь", ("мышь", "мышка", "mouse")),
    ("CAM", "Веб-камера", ("веб-камера", "веб камера", "web-камера", "webcam", "web camera")),
    ("HPH", "Наушники", ("наушник", "гарнитур", "headset", "headphone")),
    ("SPK", "Акустика / колонки", ("акустическ", "колонк", "speaker", "аудиосистем")),
    ("MFP", "МФУ (принтер + сканер)", ("принтер / сканер", "принтер сканер", "принтер/сканер", "мфу", "mfp")),
    ("PRN", "Принтер", ("принтер", "printer")),
    ("SCN", "Сканер", ("сканер", "scanner")),
    ("PLT", "Плоттер", ("плоттер", "plotter")),
    ("NVR", "Видеорегистратор", ("видеорегистратор", "nvr", "dvr")),
    ("AP", "Точка доступа", ("точка доступа", "точки доступа", "access point")),
    ("SW", "Коммутатор / свитч", ("коммутатор", "kоммутатор", "свитч", "switch")),
    ("RTR", "Роутер", ("роутер", "router", "маршрутизатор", "gpon", "network terminal")),
    ("TEL", "Стационарный телефон", ("телефон",)),
    ("UPS", "ИБП", ("бесперебойн", "ибп", "ups")),
    ("AVR", "Стабилизатор напряжения", ("регулятор напряжения", "стабилизатор", "avr")),
    ("AC", "Кондиционер", ("кондиционер", "сплит-систем")),
    ("REF", "Холодильник", ("холодильник",)),
    ("WC", "Кулер для воды", ("куллер", "кулер", "cooler")),
    ("CFM", "Кофемашина", ("кофемашина", "кофеварка")),
    ("KTL", "Электрочайник", ("чайник",)),
    ("TV", "Телевизор", ("телевизор", "tv")),
]

FALLBACK_PREFIX = "INV"

# Ключевые слова ищутся с границей слова слева. Без этого короткие
# латинские обозначения бьют по случайным подстрокам: "ups" нашлось бы в
# "groups", а "tv" — внутри "AVTECH", превратив монитор в телевизор.
# Правой границы нет намеренно — половина ключей это основы ("бесперебойн",
# "акустическ", "колонк"), которые должны ловить любое окончание.
_PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    (prefix, re.compile("|".join(r"\b" + re.escape(word) for word in keywords)))
    for prefix, _label, keywords in ASSET_CODE_RULES
]

_NUMBER_RE = re.compile(r"^(?:[A-Za-z]+-)?(\d+)$")


def _haystack(category: str, name: str) -> str:
    """Строка, по которой ищутся ключевые слова.

    Категория и наименование склеиваются, потому что тип техники бывает
    виден только в одном из них: у ИБП UPS-0004 категория "Периферийные
    устройства", а "Источник Бесперебойного Питания" — в названии.

    Схлопывание пробелов лечит реальный разнобой в базе: там соседствуют
    "Принтер / Сканер" и "Принтер  Сканер" с двумя пробелами.
    """
    combined = f"{category or ''} {name or ''}".lower().replace("ё", "е")
    return re.sub(r"\s+", " ", combined)


def guess_prefix(category: str, name: str) -> str:
    """Буквенное обозначение по категории и наименованию техники.

    Возвращает FALLBACK_PREFIX, если не сработало ни одно правило.
    """
    haystack = _haystack(category, name)
    for prefix, pattern in _PATTERNS:
        if pattern.search(haystack):
            return prefix
    return FALLBACK_PREFIX


def next_number(connection: sqlite3.Connection) -> int:
    """Следующий свободный номер — максимум по всей базе плюс один.

    Числа берутся из обоих форматов, которые встречаются в базе: и из
    "NB-0021", и из голого "181". До миграции 028 они соседствуют, и
    настоящим максимумом оказывается как раз голый номер.

    Освободившиеся номера не переиспользуются: счётчик только растёт,
    иначе номер списанной техники уехал бы на новую.
    """
    highest = 0
    for row in connection.execute(
        "SELECT inventory_number FROM assets WHERE inventory_number IS NOT NULL AND inventory_number != ''"
    ):
        match = _NUMBER_RE.match(str(row["inventory_number"]).strip())
        if match:
            highest = max(highest, int(match.group(1)))
    return highest + 1


def assign_inventory_number(connection: sqlite3.Connection, category: str, name: str) -> str:
    """Готовый инвентарный номер вида ``NB-0051`` для новой техники.

    Вызывать только внутри транзакции под STATE_LOCK: между чтением
    максимума и вставкой строки не должно вклиниться другое создание.
    """
    return f"{guess_prefix(category, name)}-{next_number(connection):04d}"


def reference() -> list[dict]:
    """Справочник в виде, пригодном для отправки клиентам.

    Порядок совпадает с ASSET_CODE_RULES, потому что клиент повторяет по
    этому списку ту же догадку и обязан получить тот же ответ.
    """
    return [
        {"prefix": prefix, "label": label, "keywords": list(keywords)}
        for prefix, label, keywords in ASSET_CODE_RULES
    ]
